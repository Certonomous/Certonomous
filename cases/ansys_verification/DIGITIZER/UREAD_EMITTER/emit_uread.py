# CALIBRATION -- ORCHESTRATION ONLY.  Every arithmetic step below is a call into
# the frozen bytes.  This function owns NO reading algorithm and NO statistic.
# It mirrors digitize_calibrate_r2.calibrate_r2():161-190 with the spec, station
# and quantity supplied per case instead of hard-wired to dc.default_spec().
# --parity proves the mirror is exact.
# =============================================================================
def calibrate_for_spec(spec, kind, statistic, n, x_station=None, sublocator=False,
                       verbose=False):
    if kind not in ("value", "position"):
        refuse("kind must be 'value' or 'position'; got %r" % kind)
    if n < 20:
        refuse("S25.3 requires N >= 20 calibration plates; got %d" % n)
    labels = dc.labels_of(spec)
    if kind == "value":
        if x_station is None:
            refuse("a value read needs an x_station (the abscissa the gate reads at)")
        q = dc.ValueQuantity(spec, float(x_station))
    else:
        q = (r2.PositionQuantityParabolic(spec) if sublocator else dc.PositionQuantity(spec))

    errs, fam0 = [], None
    for i in range(n):
        feat_x, kw = dc.cal_plate_params(i)
        cf = dc.nozzle_curve(spec, feat_x, **kw)
        rd = dc.digitize(dc.render_plate(spec, cf, 0.0), labels)   # AXIS PLANT inside
        if kind == "value":
            errs.append(q.measure(rd) - float(cf(np.array([q.x_station]))[0]))
        else:
            errs.append(q.measure(rd) - feat_x)
        if i == 0:
            fam0 = (cf, feat_x, kw)
    cf0, feat0, kw0 = fam0

    if kind == "value":
        control_render = lambda d: dc.render_plate(spec, cf0, y_displace=d)
        control_truth  = float(cf0(np.array([q.x_station]))[0])
    else:
        control_render = lambda d: dc.render_plate(spec, dc.nozzle_curve(spec, feat0 + d, **kw0), 0.0)
        control_truth  = feat0

    rep = r2._grade_quantity(spec, labels, q, errs, control_render, control_truth,
                             statistic, verbose)      # <-- FROZEN grader, frozen plants

    # shared AXIS negatives, exactly as calibrate_r2:184-190
    lspec = dc.default_spec(x_log=True)
    log_caught = dc._neg_control_refuses(lambda: dc.digitize(
        dc.render_plate(lspec, dc.nozzle_curve(lspec, 5.0), 0.0),
        {**dc.labels_of(lspec), "x_log": False}))
    flip_caught = dc._neg_control_refuses(lambda: dc.digitize(
        dc.render_plate(spec, cf0, 0.0), labels, {"force_pair_flip": True}))
    if not (log_caught and flip_caught):
        rep = dict(rep); rep["verdict"] = "NOT A RESULT"
        rep["reason"] = "shared AXIS negative not caught"
    return rep, {"log_as_linear_caught": log_caught, "planted_flip_caught": flip_caught}


def _spec_record(spec):
    """The ANSWER-BLIND format, serialised in full (S28.6).  Every field here is
    measurable from the plate WITHOUT reading the plotted curve."""
    return {"dpi": spec.dpi, "w_px": spec.w, "h_px": spec.h, "margin_px": spec.margin,
            "interior_w_px": float(spec.bx1 - spec.bx0),
            "interior_h_px": float(spec.by1 - spec.by0),
            "x_range": [spec.x0, spec.x1], "y_range": [spec.y0, spec.y1],
            "x_ticks": list(spec.x_ticks), "y_ticks": list(spec.y_ticks),
            "x_log": spec.x_log, "y_log": spec.y_log,
            "x_orient": spec.x_orient, "y_orient": spec.y_orient,
            "line_width_px": spec.line_width, "tick_len_px": spec.tick_len}


