REQUIRED_TOP  = ("dim", "units", "u_read", "statistic", "verdict",
                 "terms", "plate_interior_px_h", "y_span_data_units")
REQUIRED_TERM = ("term_A", "half_spread", "pixel_floor", "max")


def _assert_contract(d, where):
    """Re-assert on the ARTIFACT what the consumer will assert (L-221/L-222: a
    lesson is not applied until every call site asserts it).  Producer-side."""
    for k in REQUIRED_TOP:
        if k not in d:
            refuse("%s: artifact missing required top-level key %r" % (where, k))
    t = d["terms"]
    if not isinstance(t, dict):
        refuse("%s: 'terms' is %s, not an object" % (where, type(t).__name__))
    for k in REQUIRED_TERM:
        if k not in t:
            refuse("%s: 'terms' missing required sub-key %r" % (where, k))
    if d["units"] in PLACEHOLDER_UNITS:
        refuse("%s: units=%r is the frozen instrument's dimensionless placeholder. "
               "S28.2 requires every S25.4 term in the GATED QUANTITY'S OWN UNITS; "
               "the per-case registration must declare the physical unit"
               % (where, d["units"]))
    u = d["u_read"]
    if not isinstance(u, float) or not math.isfinite(u) or not (u > 0.0):
        refuse("%s: u_read is not a positive finite float: %r" % (where, u))
    span = float(d["y_span_data_units"])
    ipx  = float(d["plate_interior_px_h"])
    if not (span > 0.0) or not (ipx > 0.0):
        refuse("%s: span %r / interior_px %r must both be positive" % (where, span, ipx))
    floor = span / ipx
    if abs(float(t["pixel_floor"]) - floor) > 1e-12 * max(1.0, floor):
        refuse("%s: recorded pixel_floor %.17g != span/interior_px %.17g"
               % (where, float(t["pixel_floor"]), floor))
    three = (float(t["term_A"]), float(t["half_spread"]), floor)
    if abs(u - max(three)) > 1e-12 * max(1.0, u):
        refuse("%s: u_read %.17g != max(term_A, half_spread, pixel_floor) %.17g (S25.4)"
               % (where, u, max(three)))
    if d["statistic"] not in ("rms", "max", "p95"):
        refuse("%s: unknown statistic %r" % (where, d["statistic"]))
    if d["statistic"] == "rms" and not (float(t["max"]) < floor):
        refuse("%s: S29.3 rms INADMISSIBLE -- max per-plate %.17g >= pixel floor %.17g"
               % (where, float(t["max"]), floor))
    return True


