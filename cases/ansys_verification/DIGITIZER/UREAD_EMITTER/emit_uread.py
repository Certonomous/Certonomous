# THE WRITER.  Atomic, then READ BACK FROM DISK AND RE-VERIFIED.
# =============================================================================
def _serialize(payload):
    return json.dumps(_jsonable(payload), indent=2, sort_keys=True).encode("utf-8") + b"\n"


def _sha256_bytes(b):
    return hashlib.sha256(b).hexdigest()


def _sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for blk in iter(lambda: fh.read(65536), b""):
            h.update(blk)
    return h.hexdigest()


def _write_atomic(path, blob):
    d = os.path.dirname(os.path.abspath(path))
    os.makedirs(d, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=d, prefix=".uread_", suffix=".tmp")
    try:
        with os.fdopen(fd, "wb") as fh:
            fh.write(blob)
            fh.flush()
            os.fsync(fh.fileno())
        # mkstemp creates 0600.  A committed lab artifact must be readable like
        # every other file beside it, so the mode is set explicitly rather than
        # inherited from the temp-file API.
        os.chmod(tmp, 0o644)
        os.replace(tmp, path)
    except Exception:
        try: os.unlink(tmp)
        except OSError: pass
        raise


def _deep_equal(a, b, _path="$"):
    """Exact equality, floats included.  json round-trips binary64 exactly in
    py3 (shortest-repr), so a difference here is a real difference, not noise."""
    if type(a) is not type(b):
        if not (isinstance(a, (int, float)) and isinstance(b, (int, float))
                and not isinstance(a, bool) and not isinstance(b, bool)):
            return False, _path
    if isinstance(a, dict):
        if set(a) != set(b):
            return False, _path
        for k in a:
            ok, p = _deep_equal(a[k], b[k], "%s.%s" % (_path, k))
            if not ok:
                return False, p
        return True, _path
    if isinstance(a, list):
        if len(a) != len(b):
            return False, _path
        for i, (x, y) in enumerate(zip(a, b)):
            ok, p = _deep_equal(x, y, "%s[%d]" % (_path, i))
            if not ok:
                return False, p
        return True, _path
    if isinstance(a, float) or isinstance(b, float):
        return (float(a) == float(b)), _path
    return (a == b), _path


def _verify_on_disk(path, expected_payload, expected_sha, where):
    """THE VERIFIER.  Everything the plant control is used to prove has power.
    Refuses on: sha drift, unreadable JSON, ANY field difference, contract break."""
    if not os.path.isfile(path):
        refuse("%s: artifact not on disk after write: %s" % (where, path))
    got_sha = _sha256_file(path)
    if got_sha != expected_sha:
        refuse("%s: sha256 on disk %s != written %s" % (where, got_sha, expected_sha))
    try:
        with open(path) as fh:
            back = json.load(fh)
    except Exception as e:
        refuse("%s: artifact on disk is not readable JSON: %s" % (where, e))
    ok, p = _deep_equal(_jsonable(expected_payload), back)
    if not ok:
        refuse("%s: read-back differs from what was written, first at %s" % (where, p))
    _assert_contract(back, where + " (read-back)")
    return back, got_sha


# =============================================================================
# RULE 3 -- THE PLANTED-PERTURBATION CONTROL ON THE PERSISTENCE PATH.
#
# "A zero from a reader not shown able to see a non-zero is not evidence."  The
# persistence path is a reader as much as a writer: it claims a value reached
# disk.  So on EVERY emit, before the real artifact is written:
#
#   ARM A  positive   -- a KNOWN NON-ZERO (PERSIST_PLANT) is written through the
#                        PRODUCTION writer and read back FROM DISK; it must be
#                        recovered EXACTLY, in the u_read field itself and in a
#                        tag field.  If it cannot be seen, the emitter REFUSES.
#   ARM B  planted    -- S35.2: a control that cannot fail has no power, so the
#          FAILURE       FAILURE IS PLANTED.  The artifact on disk is corrupted
#                        (u_read -> 0.0) and the expected sha is RECOMPUTED from
#                        the corrupted file, so the sha arm cannot catch it and
#                        ONLY the field-by-field read-back compare can.  The
#                        verifier MUST refuse.  If it does not, the verifier has
#                        no power and the emitter REFUSES.
#   ARM C  zero       -- a payload carrying u_read = 0.0 must be refused by the
#                        contract check, mirroring the consumer's :262 guard.
#   ARM D  sha        -- a byte appended after the write must be caught by the
#                        sha arm alone.
#
# All four run in a temp directory and touch nothing under the case.
# =============================================================================
def persistence_plant_control(verbose=True):
    tmp = tempfile.mkdtemp(prefix="uread_plant_")
    try:
        base = {
            "dim": "value", "units": "m/s", "statistic": "max", "verdict": "PASS",
            "u_read": PERSIST_PLANT, "plant_tag": PLANT_TAG,
            "plate_interior_px_h": 495.0, "y_span_data_units": 2.5,
            "terms": {"term_A": PERSIST_PLANT, "half_spread": 1.0e-9,
                      "pixel_floor": 2.5 / 495.0, "max": PERSIST_PLANT},
            "nested": {"deep": {"band_ok": np.float64(1.0) <= 2.0}},   # the np.bool_
        }
        # ARM A -- positive: the known non-zero must survive the round trip exactly.
        pa = os.path.join(tmp, "arm_a.json")
        blob = _serialize(base)
        _write_atomic(pa, blob)
        back, sha = _verify_on_disk(pa, base, _sha256_bytes(blob), "PLANT ARM A")
        if back["u_read"] != PERSIST_PLANT or back["plant_tag"] != PLANT_TAG:
            refuse("PLANT ARM A: planted %.17g not recovered from disk (got %r) -- the "
                   "persistence path cannot be shown able to record a known non-zero, "
                   "so nothing it writes is evidence (rule 3)"
                   % (PERSIST_PLANT, back.get("u_read")))
        if back["nested"]["deep"]["band_ok"] is not True:
            refuse("PLANT ARM A: np.bool_ did not round-trip as a JSON true")
        arm_a = True

        # ARM B -- PLANTED FAILURE: corrupt the file, recompute the sha from the
        # corrupted bytes so the sha arm is disarmed, and require a refusal anyway.
        pb = os.path.join(tmp, "arm_b.json")
        _write_atomic(pb, blob)
        with open(pb) as fh:
            damaged = json.load(fh)
        damaged["u_read"] = 0.0
        dblob = json.dumps(damaged, indent=2, sort_keys=True).encode("utf-8") + b"\n"
        _write_atomic(pb, dblob)
        arm_b = False
        try:
            _verify_on_disk(pb, base, _sha256_bytes(dblob), "PLANT ARM B")
        except Refuse:
            arm_b = True
        if not arm_b:
            refuse("PLANT ARM B: the read-back comparison did NOT refuse a corrupted "
                   "artifact whose sha was recomputed -- the verifier has no power "
                   "and its passing on a clean file proves nothing (S35.2)")

        # ARM C -- a zero u_read must be refused by the contract, at the producer.
        zero = dict(base); zero["u_read"] = 0.0
        arm_c = False
        try:
            _assert_contract(_jsonable(zero), "PLANT ARM C")
        except Refuse:
            arm_c = True
        if not arm_c:
            refuse("PLANT ARM C: a zero u_read was accepted by the contract check")

        # ARM D -- sha arm alone: append one byte after a clean write.
        pd = os.path.join(tmp, "arm_d.json")
        _write_atomic(pd, blob)
        with open(pd, "ab") as fh:
            fh.write(b" ")
        arm_d = False
        try:
            _verify_on_disk(pd, base, _sha256_bytes(blob), "PLANT ARM D")
        except Refuse:
            arm_d = True
        if not arm_d:
            refuse("PLANT ARM D: a one-byte append was not caught by the sha arm")

        if verbose:
            print("PERSIST PLANT: A(positive, %.6g recovered from disk)=%s  "
                  "B(planted failure, sha disarmed)=%s  C(zero refused)=%s  "
                  "D(one-byte append caught)=%s"
                  % (PERSIST_PLANT, arm_a, arm_b, arm_c, arm_d))
        return {"planted": PERSIST_PLANT, "arm_A_positive": arm_a,
                "arm_B_planted_failure_refused": arm_b, "arm_C_zero_refused": arm_c,
                "arm_D_sha_append_caught": arm_d}
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


