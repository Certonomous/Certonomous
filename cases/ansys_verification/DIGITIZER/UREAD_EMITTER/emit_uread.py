# --parity : DEMONSTRATE (not assert) that this file changes no reading number.
# =============================================================================
def parity(n=None, verbose=True):
    assert_frozen()
    n = n or dc.N_CAL
    frozen_rep = r2.calibrate_r2(n=n, sublocator=False, out_dir=None, verbose=False)
    ok = True
    for kind, key, stat, xs in (("value", "value", "rms", dc.X_STATION),
                                ("position", "position", "max", None)):
        mine, _ = calibrate_for_spec(dc.default_spec(), kind, stat, n,
                                     x_station=xs, sublocator=False, verbose=False)
        theirs = frozen_rep[key]
        same, where = _deep_equal(_jsonable(mine), _jsonable(theirs))
        print("PARITY %-8s frozen u_read=%.17g   this file=%.17g   full-report identical: %s%s"
              % (kind, float(theirs["u_read"]), float(mine["u_read"]), same,
                 "" if same else "  (first difference at %s)" % where))
        ok = ok and same
    print("PARITY: %s" % ("IDENTICAL -- EVERY REPORTED NUMBER IS THE FROZEN GRADER'S. "
                          "(This file does contain the error-residual loop, which is "
                          "arithmetic; this parity result is what makes that safe.)"
                          if ok else "DIVERGENCE ABOVE"))
    return 0 if ok else 1


def selftest(verbose=True):
    ok = True
    f = assert_frozen()
    print("SELFTEST 1 frozen blobs pinned: R1=%s R2=%s" % (f["r1_blob"][:12], f["r2_blob"][:12]))
    p = persistence_plant_control(verbose=True)
    ok = ok and all(p[k] for k in ("arm_A_positive", "arm_B_planted_failure_refused",
                                   "arm_C_zero_refused", "arm_D_sha_append_caught"))
    print("SELFTEST 2 persistence plants: all four arms = %s" % ok)
    # 3) the S36 crash object is now serialisable, and the frozen handler still is not
    crash = {"a": {"b": {"band_ok": np.float64(1.0) <= 2.0}}}
    frozen_handler_fails = False
    try:
        json.dumps(crash, default=lambda o: float(o) if isinstance(o, np.floating) else o)
    except ValueError:
        frozen_handler_fails = True
    mine_ok = json.dumps(_jsonable(crash)) == '{"a": {"b": {"band_ok": true}}}'
    print("SELFTEST 3 GRADE_R2.err crash: frozen handler still raises=%s ; _jsonable encodes=%s"
          % (frozen_handler_fails, mine_ok))
    ok = ok and frozen_handler_fails and mine_ok
    # 4) contract refuses each required key's absence, one at a time
    good = {"dim": "value", "units": "m/s", "u_read": 2.5 / 495.0, "statistic": "max",
            "verdict": "PASS", "plate_interior_px_h": 495.0, "y_span_data_units": 2.5,
            "terms": {"term_A": 1e-9, "half_spread": 1e-9, "pixel_floor": 2.5 / 495.0,
                      "max": 1e-9}}
    _assert_contract(good, "SELFTEST 4 baseline")
    missing_all = True
    for k in REQUIRED_TOP:
        d = dict(good); d.pop(k)
        try:
            _assert_contract(d, "x"); missing_all = False
            print("   NOT REFUSED on missing top-level %r" % k)
        except Refuse:
            pass
    for k in REQUIRED_TERM:
        d = dict(good); d["terms"] = dict(good["terms"]); d["terms"].pop(k)
        try:
            _assert_contract(d, "x"); missing_all = False
            print("   NOT REFUSED on missing terms.%r" % k)
        except Refuse:
            pass
    print("SELFTEST 4 contract refuses every single missing key (%d top + %d term): %s"
          % (len(REQUIRED_TOP), len(REQUIRED_TERM), missing_all))
    ok = ok and missing_all
    # 5) placeholder units and a broken S25.4 max are refused
    bad_u = dict(good); bad_u["units"] = "y-data"
    r5a = False
    try: _assert_contract(bad_u, "x")
    except Refuse: r5a = True
    bad_m = dict(good); bad_m["u_read"] = 1e-9          # < pixel floor -> not the max
    r5b = False
    try: _assert_contract(bad_m, "x")
    except Refuse: r5b = True
    print("SELFTEST 5 refuses placeholder units=%s ; refuses u_read != max-of-three=%s" % (r5a, r5b))
    ok = ok and r5a and r5b
    print("SELFTEST: %s" % ("ALL PASS" if ok else "FAILURES ABOVE"))
    return 0 if ok else 1


