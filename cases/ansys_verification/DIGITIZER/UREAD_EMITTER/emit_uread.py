# =============================================================================
# JSON NORMALISATION -- the S36/GRADE_R2.err crash, repaired OUTSIDE frozen bytes.
# Exhaustive and REFUSING, never a passthrough default= that can loop.
# =============================================================================
def _jsonable(o, _path="$"):
    if isinstance(o, (str, int, float, bool)) or o is None:
        if isinstance(o, float) and not math.isfinite(o):
            refuse("non-finite float at %s: %r -- JSON cannot carry it and a NaN "
                   "u_read term must never reach a gate" % (_path, o))
        return o
    if isinstance(o, np.bool_):          # <-- THE CRASH.  Checked BEFORE np.integer:
        return bool(o)                   #     np.bool_ is not np.integer, but order
    if isinstance(o, np.integer):        #     is stated so a reader need not check.
        return int(o)
    if isinstance(o, np.floating):
        return _jsonable(float(o), _path)
    if isinstance(o, np.ndarray):
        return [_jsonable(v, "%s[%d]" % (_path, i)) for i, v in enumerate(o.tolist())]
    if isinstance(o, dict):
        out = {}
        for k, v in o.items():
            if not isinstance(k, str):
                refuse("non-string JSON key at %s: %r" % (_path, k))
            out[k] = _jsonable(v, "%s.%s" % (_path, k))
        return out
    if isinstance(o, (list, tuple)):
        return [_jsonable(v, "%s[%d]" % (_path, i)) for i, v in enumerate(o)]
    refuse("unserialisable object at %s: type %s -- this emitter REFUSES rather "
           "than handing json an object it cannot encode (that passthrough is the "
           "GRADE_R2.err circular-reference crash)" % (_path, type(o).__name__))


